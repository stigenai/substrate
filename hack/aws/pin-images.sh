# Pin the control plane images of the aws overlay by digest.
# Usage: hack/aws/pin-images.sh [TAG]
# Resolve ghcr.io/stigenai/substrate/<binary>:TAG to a digest with crane. Then
# rewrite manifests/ate-install/aws/images/kustomization.yaml.

set -o errexit -o nounset -o pipefail

TAG="${1:-v0.3.0-stigenai.2}"
REPO="ghcr.io/stigenai/substrate"
ROOT="$(git rev-parse --show-toplevel)"
OUT="${ROOT}/manifests/ate-install/aws/images/kustomization.yaml"

{
  sed -n '3,15p' "${BASH_SOURCE[0]}"
  echo
  echo "apiVersion: kustomize.config.k8s.io/v1alpha1"
  echo "kind: Component"
  echo
  echo "# Generated by hack/aws/pin-images.sh ${TAG}. Do not edit by hand."
  echo "images:"
  for bin in ateapi atecontroller atelet atenet; do
    digest="$(crane digest "${REPO}/${bin}:${TAG}")"
    echo "  - name: ko://github.com/agent-substrate/substrate/cmd/${bin}"
    echo "    newName: ${REPO}/${bin}"
    echo "    digest: ${digest}"
  done
} >"${OUT}"
